"""文案價格解析的測試。

每一筆 intro 都是真實資料裡實際出現過的字串 (從 data/coupons.json 抄出來的),
不是我編的。第一版正則因為要求數字後面必須接「元」, 在 '=NT$62(原價NT$133元)'
這種寫法上跳過券價抓到原價, 20 張券被誤判成不一致 —— 那些案例全部收在這裡。

跑法:
    py -3.10 -m pytest tests/test_intro_price.py -q
"""
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'scripts'))

from intro_price import parse_intro_prices, reconcile  # noqa: E402


@pytest.mark.parametrize('intro,expected', [
    # 標準寫法: 等號 + NT$ + 元, 原價在括號裡
    ('5塊咔啦脆雞(桶)+1盒原味蛋撻禮盒(6入)+8塊上校雞塊+2杯冰無糖綠茶(小)=NT$499元(原價$813)',
     (499, 813)),
    # 等號後面沒有「元」, 原價帶 NT —— 這組就是害第一版抓錯的寫法
    ('【點心盒B:10顆雙色轉轉QQ球+1份香酥脆薯(小)】+1杯冰無糖綠茶(小)=NT$62(原價NT$133元)',
     (62, 133)),
    ('8塊上校雞塊+1杯冰無糖綠茶(小)=NT$69(原價NT$133元)', (69, 133)),
    # 完全沒有等號, 券價直接寫 $88元
    ('1塊咔啦脆雞+1份香酥脆薯(小)+1杯立頓檸檬風味紅茶(中)$88元(原價NT$150元)', (88, 150)),
    # 沒有 NT 也沒有元
    ('飲料5選2:1杯冰奶茶或1杯百事可樂(中)或1杯七喜(中)=$38', (38, None)),
    # 原價沒有「元」
    ('10顆雙色轉轉QQ球+1杯冰無糖綠茶(小) =NT$39(原價NT$92)', (39, 92)),
    # 用「合計」而不是等號
    ('買1杯經典冰奶茶+1元再享1杯經典冰奶茶 此優惠合計$39元', (39, None)),
    # 原價的其他說法
    ('2份薯餅+1杯冰無糖紅茶(小)=NT$42元(最高價值$113元)', (42, 113)),
    ('2個薯餅+1杯立頓檸檬風味紅茶(小)=NT$49(市價NT$113)', (49, 113)),
    ('2塊咔啦脆雞+【點心盒E:2顆原味蛋撻】=NT$147元(最高價值$240元)', (147, 240)),
    # 「省 N」不是原價, 是省下的金額 -> 原價 = 券價 + 省
    ('買1杯經典熱奶茶(中)  送1杯經典熱奶茶(中)=NT$38元(省NT$38元)', (38, 76)),
    # 同一句裡有兩個金額, 券價要抓 40 不能抓成 38; 原價 = 40 + 38
    ('"買1杯玉米濃湯(小)=NT$40 送1杯冰無糖綠茶(中)(省$38) *若門市無法提供..."', (40, 78)),
    # 明講的原價優先, 不可以再把「省」加上去
    ('買1份薯餅+1杯冰無糖綠茶(小)=NT$49元(最高價值$73元) 送1份薯餅(省$40)', (49, 73)),
    # 只有「省」沒有券價時, 不能亂回推原價
    ('本活動可省NT$40元', (None, None)),
    # 文案同時有「單項價」與「合計價」, 要取合計 (等號後面的 199 只是其中一項)
    ('買1盒原味蛋撻禮盒(6入)=$199元+6元即享100%蘋果汁 此套餐合計205元', (205, None)),
    ('買1盒原味蛋撻禮盒(6入)=$199元+10元即享1.25L可樂乙瓶 此套餐合計209元', (209, None)),
    # 沒有任何金額
    ('本券限內用', (None, None)),
    ('', (None, None)),
])
def test_parse_intro_prices(intro, expected):
    assert parse_intro_prices(intro) == expected


class TestReconcile:
    def test_對得上(self):
        assert reconcile(499, '...=NT$499元(原價$813)') == ('match', 813)

    def test_對不上要講清楚兩邊各是多少(self):
        status, list_price = reconcile(500, '...=NT$499元(原價$813)')
        assert status == 'mismatch: 公式 500 vs 文案 499'
        assert list_price == 813

    def test_文案沒有價格時仍要拿到原價(self):
        assert reconcile(88, '一些說明文字(原價NT$150元)') == ('unparsed', 150)

    def test_文案什麼都沒有(self):
        assert reconcile(88, '') == ('unparsed', None)
